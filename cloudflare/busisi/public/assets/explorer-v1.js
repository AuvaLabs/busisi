import { renderDistrictContext } from './district-context-v1.js';

(() => {
  const root = document.querySelector('[data-explorer]');
  if (!root) return;

  const form = root.querySelector('[data-explorer-form]');
  const results = root.querySelector('[data-explorer-results]');
  const count = root.querySelector('[data-explorer-count]');
  const total = root.querySelector('[data-explorer-total]');
  const status = root.querySelector('[data-explorer-status]');
  const more = root.querySelector('[data-explorer-more]');
  const reset = root.querySelector('[data-explorer-reset]');
  const sort = root.querySelector('[data-explorer-sort]');
  const description = root.querySelector('[data-explorer-description]');
  const tabs = [...root.querySelectorAll('[data-explorer-view]')];
  const peso = new Intl.NumberFormat('en-PH', { style: 'currency', currency: 'PHP' });

  const views = Object.freeze({
    budgets: {
      endpoint: '/api/v1/budgets',
      description: 'GAA appropriations reproduced from the archived official snapshot.',
      sorts: [['amount_desc', 'Largest appropriation'], ['year_desc', 'Newest fiscal year'], ['title_asc', 'Description A to Z']],
    },
    delivery: {
      endpoint: '/api/v1/delivery',
      description: 'DPWH delivery records reproduced separately from the archived official snapshot.',
      sorts: [['budget_desc', 'Largest project budget'], ['year_desc', 'Newest fiscal year'], ['title_asc', 'Description A to Z']],
    },
    candidates: {
      endpoint: '/api/v1/candidates',
      description: 'Unreviewed candidate links generated by deterministic similarity rules. They are not findings.',
      sorts: [['score_desc', 'Strongest match evidence'], ['difference_desc', 'Largest amount difference'], ['year_desc', 'Newest fiscal year']],
    },
    reviewed: {
      endpoint: '/api/v1/projects',
      description: 'Human-reviewed linkage cases, including quarantined candidates.',
      sorts: [['appropriation_desc', 'Largest appropriation'], ['difference_desc', 'Largest amount difference'], ['year_desc', 'Newest fiscal year'], ['title_asc', 'Project A to Z']],
    },
  });

  let view = 'budgets';
  let nextCursor = null;
  let controller = null;

  const appendText = (parent, tag, value, className) => {
    const element = document.createElement(tag);
    element.textContent = value;
    if (className) element.className = className;
    parent.append(element);
    return element;
  };

  const link = (parent, label, href) => {
    const anchor = appendText(parent, 'a', label);
    anchor.href = href;
    if (href.startsWith('http')) {
      anchor.target = '_blank';
      anchor.rel = 'noopener noreferrer';
    }
    return anchor;
  };

  const amountBlock = (card, label, centavos) => {
    const block = document.createElement('div');
    block.className = 'record-amount';
    appendText(block, 'span', label);
    appendText(block, 'strong', peso.format(Number(centavos || 0) / 100));
    card.append(block);
  };

  const baseCard = (type, heading) => {
    const card = document.createElement('article');
    card.className = 'record-card';
    const main = document.createElement('div');
    appendText(main, 'span', type, `record-type ${type === 'Unreviewed candidate' ? 'candidate' : type === 'Reviewed dossier' ? 'reviewed' : ''}`);
    appendText(main, 'h2', heading);
    card.append(main);
    return { card, main };
  };

  const renderBudget = (record) => {
    const { card, main } = baseCard('GAA appropriation', record.description);
    const meta = appendText(main, 'div', '', 'record-meta');
    appendText(meta, 'span', `FY ${record.fiscal_year}`);
    appendText(meta, 'span', record.budget_line_id.split('|')[0]);
    appendText(main, 'p', record.family_label);
    const links = appendText(main, 'div', '', 'record-links');
    link(links, 'Open appropriation record', record.reader_source_url);
    link(links, `View FY ${record.fiscal_year} GAA documents`, record.official_documents_url);
    link(links, 'How this record was sourced', '/methodology/#source-policy');
    amountBlock(card, 'Appropriation', record.amount_centavos);
    return card;
  };

  const renderDelivery = (record) => {
    const { card, main } = baseCard('DPWH delivery record', record.description);
    const meta = appendText(main, 'div', '', 'record-meta');
    appendText(meta, 'span', `FY ${record.fiscal_year}`);
    appendText(meta, 'span', `Contract ${record.contract_id}`);
    appendText(meta, 'span', record.location || 'Location not stated');
    appendText(main, 'p', record.source_of_funds || 'Funding source not stated');
    main.append(renderDistrictContext(record.district_context));
    const links = appendText(main, 'div', '', 'record-links');
    link(links, 'Open delivery record', record.reader_source_url);
    link(links, 'How this record was sourced', '/methodology/#source-policy');
    amountBlock(card, 'Project budget', record.budget_centavos);
    return card;
  };

  const renderCandidate = (record) => {
    const { card, main } = baseCard('Unreviewed candidate', record.budget_description);
    const meta = appendText(main, 'div', '', 'record-meta');
    appendText(meta, 'span', `FY ${record.fiscal_year}`);
    appendText(meta, 'span', `Contract ${record.contract_id}`);
    appendText(meta, 'span', `Evidence score ${record.score}`);
    appendText(main, 'p', `Possible delivery record: ${record.delivery_description}`);
    const links = appendText(main, 'div', '', 'record-links');
    link(links, 'Compare evidence', record.review_url);
    link(links, 'Review budget record', record.budget_reader_url);
    link(links, 'Review delivery record', record.delivery_reader_url);
    amountBlock(card, 'Appropriation', record.budget_amount_centavos);
    return card;
  };

  const renderReviewed = (record) => {
    const { card, main } = baseCard('Reviewed dossier', record.title);
    const meta = appendText(main, 'div', '', 'record-meta');
    appendText(meta, 'span', `FY ${record.fiscal_year}`);
    appendText(meta, 'span', `Contract ${record.contract_id}`);
    appendText(meta, 'span', record.status_label);
    appendText(main, 'p', record.location);
    const links = appendText(main, 'div', '', 'record-links');
    link(links, 'Open evidence dossier', `/projects/${record.slug}/`);
    amountBlock(card, 'Appropriation', record.appropriation_centavos);
    return card;
  };

  const renderers = { budgets: renderBudget, delivery: renderDelivery, candidates: renderCandidate, reviewed: renderReviewed };

  const query = (cursor) => {
    const data = new FormData(form);
    const params = new URLSearchParams();
    for (const name of ['q', 'year', 'sort']) {
      const value = String(data.get(name) || '').trim();
      if (value) params.set(name, value);
    }
    const signal = new URLSearchParams(location.search).get('signal');
    if (view === 'candidates' && signal === 'zero_budget') params.set('signal', signal);
    params.set('limit', '25');
    if (cursor) params.set('cursor', cursor);
    return params;
  };

  const syncUrl = () => {
    const params = query();
    params.delete('limit');
    params.set('view', view);
    history.replaceState(null, '', `${location.pathname}?${params.toString()}`);
  };

  const load = async ({ append = false } = {}) => {
    controller?.abort();
    controller = new AbortController();
    status.textContent = 'Loading verified snapshot data…';
    try {
      const response = await fetch(`${views[view].endpoint}?${query(append ? nextCursor : null)}`, {
        headers: { Accept: 'application/json' },
        signal: controller.signal,
      });
      if (!response.ok) throw new Error(`Data service returned ${response.status}`);
      const payload = await response.json();
      const cards = payload.data.map(renderers[view]);
      if (append) results.append(...cards);
      else results.replaceChildren(...cards);
      nextCursor = payload.meta.next_cursor;
      count.textContent = String(results.children.length);
      total.textContent = String(payload.meta.total);
      more.hidden = !nextCursor;
      status.textContent = payload.meta.review_scope === 'unreviewed_candidates'
        ? 'Showing unreviewed candidate links.'
        : 'Showing archived public source records.';
      syncUrl();
    } catch (error) {
      if (error.name === 'AbortError') return;
      results.replaceChildren();
      nextCursor = null;
      more.hidden = true;
      status.textContent = 'The data service is temporarily unavailable. No result was inferred.';
    }
  };

  const selectView = (nextView, { loadData = true } = {}) => {
    view = Object.hasOwn(views, nextView) ? nextView : 'budgets';
    tabs.forEach((tab) => tab.setAttribute('aria-selected', String(tab.dataset.explorerView === view)));
    sort.replaceChildren(...views[view].sorts.map(([value, label]) => {
      const option = document.createElement('option');
      option.value = value;
      option.textContent = label;
      return option;
    }));
    description.textContent = views[view].description;
    nextCursor = null;
    if (loadData) load();
  };

  form.addEventListener('submit', (event) => {
    event.preventDefault();
    nextCursor = null;
    load();
  });
  reset.addEventListener('click', () => {
    form.reset();
    selectView('budgets');
  });
  more.addEventListener('click', () => load({ append: true }));
  tabs.forEach((tab) => tab.addEventListener('click', () => selectView(tab.dataset.explorerView)));
  window.addEventListener('popstate', () => location.reload());

  const initial = new URLSearchParams(location.search);
  for (const name of ['q', 'year']) {
    if (initial.has(name) && form.elements[name]) form.elements[name].value = initial.get(name);
  }
  selectView(initial.get('view') || 'budgets');
})();
